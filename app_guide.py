def _allowed(roles: str, viewer: dict) -> bool:
    admin = bool(viewer.get("admin"))
    mgr = admin or str(viewer.get("role") or "") == "team_lead"
    return {"all": True, "agent": not mgr or bool(viewer.get("agent_id")), "manager": mgr, "admin": admin}.get(roles, False)


def for_viewer(viewer: dict) -> list[dict]:
    return [g for g in GUIDE if _allowed(g["roles"], viewer)]


def as_entries(viewer: dict) -> list[dict]:
    """ცოდნის ბაზის ფორმატი (ai_knowledge.rank/render_entry-სთვის)."""
    out = []
    for g in for_viewer(viewer):
        body = f"სად: {g['where']}\n" + "\n".join(f"{i}. {s}" for i, s in enumerate(g["steps"], 1)) + ("\n" + "\n".join("💡 " + t for t in g["tips"]) if g["tips"] else "")
        out.append({"kb_id": "guide:" + g["id"], "category": "app_guide", "version": "app", "title": f"{g['icon']} {g['title']}", "body": body})
    return out


def block_for(question: str, viewer: dict, k: int = 4) -> str:
    """SAIRO-სთვის: კითხვასთან ყველაზე ახლოს მყოფი სახელმძღვანელოს ჩანაწერები (აპის ფაქტობრივი ქცევა)."""
    import ai_knowledge as kn
    hits = [e for e, _ in kn.rank(question, as_entries(viewer), k=k, min_score=0.1)]
    return "\n".join(kn.render_entry(e) for e in hits)


def register(app, *, authed) -> None:
    from flask import jsonify

    @app.get("/api/guide")
    def api_guide():
        agent, admin, err = authed()
        if err:
            return err
        a = agent or {}
        return jsonify(items=for_viewer({"agent_id": a.get("agent_id"), "role": a.get("role"), "admin": bool(admin)}))
